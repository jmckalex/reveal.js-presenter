#!/usr/bin/env node
'use strict';
/*
 * Generate a channel: a random secret, and its SHA-256, which is the channel id.
 * The relay accepts a broadcast only if sha256(secret) equals the channel id.
 *
 *   node tools/make-channel.js https://relay.example.org
 *   node tools/make-channel.js https://relay.example.org --write path/to/presenter-config.js
 *
 * The secret is printed, never written: it goes in the laptop's URL as
 * ?master=<secret>.  The config file holds only the public relay and channel id.
 */
const crypto = require('crypto');
const fs = require('fs');

let relay = 'https://relay.example.org';
let out = null;
const args = process.argv.slice(2);
for (let i = 0; i < args.length; i++) {
	if (args[i] === '--write') out = args[++i];
	else if (args[i] === '--help' || args[i] === '-h') {
		console.log('usage: make-channel.js [relay-url] [--write presenter-config.js]');
		process.exit(0);
	}
	else relay = args[i];
}
relay = relay.replace(/\/+$/, '');

const sha256 = s => crypto.createHash('sha256').update(s).digest('hex');
const secret = crypto.randomBytes(16).toString('hex');
const channel = sha256(secret);
// The tablet's key for audience questions: typed once on the tablet, so it
// avoids look-alike characters (no 0, 1, I or O).  12 characters from 32
// gives 60 bits, and 256 is a multiple of 32, so b % 32 is unbiased.
const ALPHABET = '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
const key = Array.from(crypto.randomBytes(12), b => ALPHABET[b % ALPHABET.length]).join('').replace(/(.{4})(?!$)/g, '$1-');
const config = `/* Generated by tools/make-channel.js.  Public: contains no secret. */
window.PresenterConfig = {
	relay: ${JSON.stringify(relay)},
	channel: '${channel}',
	questionsKey: '${sha256(key)}',
};
`;

if (out) {
	if (fs.existsSync(out)) {
		console.error(`${out} already exists; not overwriting it (its channel would stop matching your secret).`);
		process.exit(1);
	}
	fs.writeFileSync(out, config);
	console.log(`Wrote ${out}`);
}
else {
	console.log('--- presenter-config.js ---\n' + config);
}
console.log(`Secret (keep it private; open decks with ?master=<secret>):\n  ${secret}`);
console.log(`Questions key (keep it private; enter it once on the presenter's tablet):\n  ${key}`);
console.log(`Channel id (public; already in the config above):\n  ${channel}`);
